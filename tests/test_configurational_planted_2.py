from __future__ import annotations
import csv
import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "packs" / "configurational" / "fixtures" / "planted-2"
SCRIPT = ROOT / "packs" / "configurational" / "scripts" / "qca_check.py"
LABEL = "SYNTHETIC TEST PAPER, NOT REAL RESEARCH"
CHECKS = {f"B{i}" for i in range(1, 16)} | {f"Q{i}" for i in range(1, 16)}
SETS = ["Reliable", "Protocol", "Champion", "Huddles", "Staffing", "Tenure", "Digital", "Leader"]
PLANTS = {"P1": ("B5", "Weakens a claim"), "P2": ("B14", "Weakens a claim"), "P3": ("B10", "Minor")}
DECOYS = {"D1a": "B1", "D1b": "B2", "D2": "Q4", "D3": "B7"}
MUST_NOT_RAISE = ["asks for inter-rater reliability for the crisp coding",
                  "raises the missing case descriptions under Q4 as well as B14",
                  "asks for a larger sample for statistical reasons",
                  "flags a missing PRI column"]


def _script():
    spec = importlib.util.spec_from_file_location("qca_check", SCRIPT)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _expected():
    return yaml.safe_load((FIXTURE / "expected.yaml").read_text(encoding="utf-8"))


def _records():
    return json.loads((FIXTURE / "script_inputs.json").read_text(encoding="utf-8"))


def _csv():
    with (FIXTURE / "memberships.csv").open(encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f))
    return rows[0], rows[1:]


def test_planted_2_expected_is_complete_and_labeled():
    exp = _expected()
    assert exp["synthetic"] is True and exp["owner"] == "blind-agent" and exp["label"] == LABEL
    assert exp["status"] in ("pending_planting", "ready") and exp["script_checked"] is True
    assert exp["must_not_raise"] == MUST_NOT_RAISE
    catch = {i["note"].split(":", 1)[0]: i for i in exp["must_catch"]}
    assert set(catch) == set(PLANTS)
    for pid, (check, severity) in PLANTS.items():
        assert catch[pid]["check"] == check and catch[pid]["severity"] == severity, pid
    decoys = {i["note"].split(":", 1)[0]: i for i in exp["must_not_flag"]}
    assert {k: v["check"] for k, v in decoys.items()} == DECOYS
    assert "B6" in {i["check"] for i in exp["also_fair"]}
    assert "B13" not in {i["check"] for i in exp["also_fair"]}
    for key in ("must_catch", "must_not_flag", "also_fair"):
        for item in exp[key]:
            assert {"check", "page", "locator", "note"} <= set(item), item
            assert item["check"] in CHECKS, item
            assert chr(0x2014) not in json.dumps(item), item
    plants = {(i["check"], str(i["page"]), i["locator"]) for i in exp["must_catch"]}
    locators = {i["locator"] for i in exp["must_catch"]}
    for d in exp["must_not_flag"]:
        assert (d["check"], str(d["page"]), d["locator"]) not in plants and d["locator"] not in locators, d
    tex = (FIXTURE / "planted.tex").read_text(encoding="utf-8")
    assert LABEL in tex and (FIXTURE / "planted.pdf").exists()
    assert "generated by a script" not in tex


def test_planted_2_script_raises_no_flag_and_one_rounding_sensitive_sum():
    records = _records()
    assert sorted(r["kind"] for r in records) == ["design", "fit_table", "memberships"]
    [fit] = [r for r in records if r["kind"] == "fit_table"]
    assert fit["outcome"] == "presence" and fit["crisp_outcome"] is True and len(fit["terms"]) == 2
    assert [t["raw_coverage"] for t in fit["terms"]] == ["0.12", "0.12"] and fit["solution_coverage"] == "0.25"
    results = _script().run_records(records)
    assert all(r["status"] != "invalid" for r in results), results
    assert not [r for r in results if r["flag"]]
    [b7] = [r for r in results if r["id"] == fit["id"] and r["check"] == "B7"]
    assert b7["reasons"] == ["solution_coverage_above_sum_raw_rounding_sensitive"]
    [d3] = [i for i in _expected()["must_not_flag"] if i["note"].startswith("D3:")]
    assert d3["record"] == fit["id"]
    [b5] = [r for r in results if r["kind"] == "design" and r["check"] == "B5"]
    assert b5["facts"]["logical_rows"] == 128 and b5["facts"]["least_remainder_share"] == "0.8750"
    [mem] = [r for r in results if r["kind"] == "memberships" and r["check"] == "B7"]
    assert "violations" not in mem["facts"] and mem["facts"]["recomputed_ranges"]


def test_planted_2_case_data_match_the_memberships_file():
    header, rows = _csv()
    assert header == ["unit"] + SETS and len(rows) == 16
    assert all(v in ("0", "1") for row in rows for v in row[1:])
    assert sum(row[1] == "1" for row in rows) == 8
    [mem] = [r for r in _records() if r["kind"] == "memberships"]
    assert mem["sets"] == SETS and mem["outcome"] == "Reliable" and mem["conditions"] == SETS[1:]
    assert mem["cases"] == [dict(zip(SETS, row[1:])) for row in rows]
    [fit] = [r for r in _records() if r["kind"] == "fit_table"]
    covered = []
    for t in fit["terms"]:
        lits = [(p.startswith("~"), p.lstrip("~")) for p in t["label"].split("*")]
        cases = [row for row in rows
                 if all((row[1 + SETS.index(name)] == "0") == neg for neg, name in lits)]
        assert len(cases) == 1 and cases[0][1] == "1", t["label"]
        covered.append(cases[0][0])
    assert len(set(covered)) == 2


def test_planted_2_other_reliable_units_sit_in_contradictory_rows():
    header, rows = _csv()
    [fit] = [r for r in _records() if r["kind"] == "fit_table"]
    covered = set()
    for t in fit["terms"]:
        lits = [(p.startswith("~"), p.lstrip("~")) for p in t["label"].split("*")]
        covered |= {row[0] for row in rows if all((row[1 + SETS.index(name)] == "0") == neg for neg, name in lits)}
    for row in rows:
        if row[1] == "1" and row[0] not in covered:
            assert any(o[1] == "0" and o[2:] == row[2:] for o in rows), row[0]
    assert any(i["check"] == "B6" and "0.25" in i["note"] for i in _expected()["also_fair"])


def test_planted_2_rerun_reproduces_the_data(tmp_path):
    subprocess.run([sys.executable, str(FIXTURE / "make_fixture.py"), "--out", str(tmp_path)], check=True,
                   capture_output=True)
    for name in ("memberships.csv", "script_inputs.json"):
        assert (tmp_path / name).read_bytes() == (FIXTURE / name).read_bytes(), name
